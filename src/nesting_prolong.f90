!> \file nesting_prolong.f90
!!  Conservative prolongation of parent boundary bands onto the child grid.
!!
!!  THE SPECIFICATION IS THE PYTHON.  This is a port of
!!  udprep.nesting.conservative_interpolate; that implementation, its 100+
!!  unit tests and docs/udales-nesting-spec.md define the numerics, and
!!  runmode TEST_NESTING_PROLONG cross-checks this code against reference
!!  output generated by it.  Any disagreement is a bug here.
!!
!!  WHY IN THE SOLVER.  Until now the writer prolonged offline and stored
!!  child-grid slabs, which for a refinement ratio r costs r^3 times the
!!  parent's band volume, in double precision -- 16x at r = 2 and 128x at
!!  r = 4.  Prolonging here instead lets the file carry raw parent-grid bands
!!  in single precision.  It is sound because the prolongation is conservative:
!!  child face fluxes summed over a parent face equal the parent face flux to
!!  round-off (test_nesting.py TestP2FluxIdentity), so a band whose net flux
!!  was zeroed on the PARENT grid still has zero net flux after prolongation.
!!  The per-level correction therefore stays a single f8 scalar in the header
!!  and precision costs nothing.
!!
!!  STRUCTURE.  Three separable 1-D operators, one per axis:
!!
!!    tangential axis (the component is cell centred on it)
!!        out(i) = f(idx(i)) + slope(idx(i)) * (target(i) - centre(idx(i)))
!!      with idx the parent cell containing the target and slope a central
!!      difference, one sided at the ends and mask aware (a solid neighbour is
!!      not used, so an IBM parent's in-building velocity cannot leak into the
!!      fluid cell beside it).  The slope term is dropped for prolongation
!!      "constant".
!!
!!    normal axis (the component is face staggered on it)
!!        out(i) = f(idx(i)) * wlo(i) + f(idx(i)+1) * (1 - wlo(i))
!!      with wlo snapped to exactly 1 or 0 when the target coincides with a
!!      parent face.  That snap is what makes the flux identity exact.
!!
!!  Tangential axes are applied before the normal axis so that the parent mask
!!  is still on the parent stagger while the slopes need it; the operators act
!!  on different axes, so the result is independent of their order.
!!
